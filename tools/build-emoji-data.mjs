// Builds src/pkjs/pgjs/emoji-data.js: emoji shortcode names plus the emoji each
// PebbleOS firmware tier can draw. Run with: npm run build:emoji
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const data = require("emojibase-data/en/data.json");
const github = require("emojibase-data/en/shortcodes/github.json");
const cldr = require("emojibase-data/en/shortcodes/cldr.json");
const coverage = JSON.parse(readFileSync(new URL("./pebbleos-emoji-coverage.json", import.meta.url), "utf8"));

// Emoji that shipped in Pebblegram 3.5's hand-tested list for older firmware.
// Keep them so older watches don't lose anything they already showed.
const OLD_TESTED = [
  0x231a, 0x263a, 0x2620, 0x26a7, 0x2705, 0x270b, 0x270c, 0x2728, 0x274e, 0x2757, 0x2763, 0x2764,
  0x2b50, 0x1f319, 0x1f31f, 0x1f337, 0x1f338, 0x1f33a, 0x1f340, 0x1f37a, 0x1f37b, 0x1f389, 0x1f3b6,
  0x1f3f3, 0x1f425, 0x1f440, 0x1f44d, 0x1f44e, 0x1f480, 0x1f493, 0x1f494, 0x1f495, 0x1f496, 0x1f497,
  0x1f498, 0x1f499, 0x1f49a, 0x1f49b, 0x1f49c, 0x1f49d, 0x1f49e, 0x1f49f, 0x1f4a1, 0x1f4a3, 0x1f4a5,
  0x1f4a9, 0x1f4af, 0x1f5a4, 0x1f643, 0x1f644, 0x1f64f, 0x1f917, 0x1f918, 0x1f91d, 0x1f923, 0x1f924,
  0x1f929, 0x1f92a, 0x1f92c, 0x1f92e, 0x1f970, 0x1f97a
];
for (let cp = 0x1f600; cp <= 0x1f637; cp += 1) {
  OLD_TESTED.push(cp);
}

const SKIN_TONE = /^1F3F[B-F]$/;

function key(hexcode) {
  return hexcode
    .split("-")
    .filter((part) => part !== "FE0F" && part !== "FE0E" && !SKIN_TONE.test(part))
    .map((part) => parseInt(part, 16).toString(16))
    .join("-");
}

function pick(value) {
  const list = Array.isArray(value) ? value : value ? [value] : [];
  return list.find((name) => /^[a-z0-9]/.test(name)) || list[0] || "";
}

function snake(label) {
  return String(label || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

const names = {};
for (const entry of data) {
  const k = key(entry.hexcode);
  if (!k || names[k]) {
    continue;
  }
  const name = pick(github[entry.hexcode]) || pick(cldr[entry.hexcode]) || snake(entry.label);
  if (name) {
    names[k] = name.replace(/[^a-z0-9_+-]/gi, "_").toLowerCase();
  }
}

function expand(ranges) {
  const out = [];
  for (const [start, end] of ranges) {
    for (let cp = start; cp <= end; cp += 1) {
      out.push(cp);
    }
  }
  return out;
}

function toRanges(values) {
  const out = [];
  for (const cp of [...new Set(values)].sort((a, b) => a - b)) {
    const last = out[out.length - 1];
    if (last && last[1] === cp - 1) {
      last[1] = cp;
    } else {
      out.push([cp, cp]);
    }
  }
  return out;
}

const tiers = {};
for (const [name, tier] of Object.entries(coverage.tiers)) {
  const emoji = expand(tier.emoji);
  if (name === "old") {
    emoji.push(...OLD_TESTED);
  }
  const version = tier.minFirmware.split(".").map((part) => parseInt(part, 10) || 0);
  tiers[name] = {
    minFirmware: version,
    emoji: toRanges(emoji),
    gothic: tier.gothic,
    routed: tier.routed
  };
}

const maxSequence = Math.max(...Object.keys(names).map((k) => k.split("-").length));
const output =
  "// Generated by tools/build-emoji-data.mjs. Do not edit by hand.\n" +
  "// Emoji names: emojibase-data (MIT). Watch coverage: coredevices/PebbleOS fonts.\n" +
  "module.exports = " +
  JSON.stringify({ maxSequence, names, tiers }) +
  ";\n";
writeFileSync(new URL("../src/pkjs/pgjs/emoji-data.js", import.meta.url), output);
console.log(`emoji-data.js: ${Object.keys(names).length} names, ${output.length} bytes`);
